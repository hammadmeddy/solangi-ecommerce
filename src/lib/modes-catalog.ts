export function modeProducts(mode: ModeId): DemoProduct[] {
  if (mode === "retail") return [];
  return MODE_CATALOG.filter((p) => p.mode === mode);
}

export function findModeProduct(id: string): DemoProduct | undefined {
  return MODE_CATALOG.find((p) => p.id === id);
}

export function modeLabel(mode: ModeId): string {
  switch (mode) {
    case "wholesale":
      return "Wholesale · B2B";
    case "used":
      return "Used · C2C";
    case "services":
      return "Services · C2B";
    default:
      return "Retail · B2C";
  }
}
